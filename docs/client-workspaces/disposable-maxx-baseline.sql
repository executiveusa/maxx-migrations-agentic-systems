CREATE SCHEMA auth;
CREATE SCHEMA maxx;
CREATE SCHEMA extensions;
CREATE EXTENSION pgcrypto WITH SCHEMA extensions;
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
$$;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY, aud text DEFAULT 'authenticated', role text DEFAULT 'authenticated',
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
);
CREATE TABLE maxx.organizations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE, name text NOT NULL, status text NOT NULL DEFAULT 'active',
  data_residency text DEFAULT 'us', migration_target text DEFAULT 'none',
  metadata jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
);
CREATE TABLE maxx.memberships (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  user_id uuid NOT NULL REFERENCES auth.users(id),
  role text NOT NULL, status text NOT NULL DEFAULT 'active',
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
);
CREATE TABLE maxx.projects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  slug text NOT NULL, name text NOT NULL, project_type text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  repository text, external_refs jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (organization_id,slug)
);
CREATE TABLE maxx.workflow_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id),
  status text NOT NULL DEFAULT 'queued'
);
CREATE TABLE maxx.action_proposals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id),
  status text NOT NULL DEFAULT 'proposed'
);
CREATE TABLE maxx.approvals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  action_proposal_id uuid NOT NULL REFERENCES maxx.action_proposals(id),
  status text NOT NULL DEFAULT 'pending',
  expires_at timestamptz NOT NULL DEFAULT now()+interval '24 hours'
);
CREATE TABLE maxx.run_steps (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  run_id uuid NOT NULL REFERENCES maxx.workflow_runs(id),
  status text NOT NULL DEFAULT 'queued'
);
CREATE TABLE maxx.audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id),
  actor_type text NOT NULL, actor_id text, action text NOT NULL,
  object_type text NOT NULL, object_id text,
  payload_redacted jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE maxx.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id)
);
CREATE TABLE maxx.artifacts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id)
);
CREATE TABLE maxx.context_snapshots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id)
);
CREATE TABLE maxx.evidence_receipts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id)
);
CREATE TABLE maxx.external_refs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id),
  project_id uuid REFERENCES maxx.projects(id)
);
CREATE TABLE maxx.lead_intakes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES maxx.organizations(id)
);
